const captions = { home: "cap_home", catalog: "cap_catalog", product: "cap_product", cart: "cap_cart" };
let lang = "ru";
let screen = "home";
let device = "desktop";

function applyLang(next) {
  lang = next === "en" ? "en" : "ru";
  try { localStorage.setItem("lang", lang); } catch (e) {}
  document.documentElement.lang = lang;
  document.getElementById("btn-ru").setAttribute("aria-pressed", lang === "ru");
  document.getElementById("btn-en").setAttribute("aria-pressed", lang === "en");
  document.getElementById("lang-switch").setAttribute("aria-label", lang === "ru" ? "Язык" : "Language");
  const pack = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = pack[key];
    if (value == null) return;
    const attr = el.getAttribute("data-i18n-attr");
    if (attr) el.setAttribute(attr, value);
    else el.textContent = value;
  });
  document.title = pack.title;
  const caption = document.getElementById("shot-caption");
  if (caption) caption.textContent = pack[captions[screen]];
}

function showShot() {
  document.querySelectorAll(".shot").forEach((img) => {
    const on = img.dataset.screen === screen && img.dataset.device === device;
    img.classList.toggle("is-on", on);
  });
  document.querySelectorAll("[data-screen]").forEach((btn) => {
    if (btn.tagName !== "BUTTON") return;
    btn.setAttribute("aria-pressed", btn.dataset.screen === screen);
  });
  document.querySelectorAll("[data-device]").forEach((btn) => {
    if (btn.tagName !== "BUTTON") return;
    btn.setAttribute("aria-pressed", btn.dataset.device === device);
  });
  const pack = translations[lang];
  const caption = document.getElementById("shot-caption");
  if (caption && pack[captions[screen]]) caption.textContent = pack[captions[screen]];
}

document.getElementById("btn-ru").addEventListener("click", () => applyLang("ru"));
document.getElementById("btn-en").addEventListener("click", () => applyLang("en"));

document.querySelectorAll(".shot-controls button").forEach((btn) => {
  btn.addEventListener("click", () => {
    if (btn.dataset.screen) screen = btn.dataset.screen;
    if (btn.dataset.device) device = btn.dataset.device;
    showShot();
  });
});

